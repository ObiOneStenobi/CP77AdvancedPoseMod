"""Builds src/Pose/EyelidFollowData.inc from AdvancedPoseMod logs written with the EyelidProbe ([Debug] Log=1).

The probe (Pose/FaceRig.cpp, LogEyelidProbe) was removed once the table was built; it is in the git history (1.1.0).

Usage: python tools/eyelid_follow_fit.py <advancedposemod-*.log> [more logs] > src/Pose/EyelidFollowData.inc

The probe logs, as the game animated them, the turn of both eyes and the turn / move of every eyelid bone relative to the
reference pose, and the Photo Mode facial expression (attribute 28). For each eyelid bone a piecewise linear model is fitted
on the neutral expression: change = a_down * min(pitch, 0) + a_up * max(pitch, 0) + a_yaw * yaw + c. For each expression of
the base game (0-14) the share of that movement the game keeps is measured on the eyelid root bones.
"""
import re
import sys

import numpy as np

PITCH_MIN, PITCH_MAX, YAW_MAX = -30.0, 20.8, 40.0  # how far the game turns the eyes
SETTLE = 0.6  # seconds after an expression change that are skipped (the face is still blending)
EXPRESSIONS = 15  # facial expressions of the base game


def seconds(stamp):
    h, m, s = stamp.split(":")
    return int(h) * 3600 + int(m) * 60 + float(s)


def read(paths):
    bones, rows = None, []
    for path in paths:
        expression, changed = 0, 0.0
        for line in open(path, encoding="utf-8", errors="replace"):
            stamp = line[12:24]
            if "EyelidProbe bones:" in line:
                bones = line.split("EyelidProbe bones:")[1].split()
            found = re.search(r"facial expression: (\d+)", line)
            if found:
                expression, changed = int(found.group(1)), seconds(stamp)
            if "EyelidProbe v:" in line:
                values = [float(x) for group in line.split("EyelidProbe v:")[1].split() for x in group.split(",")]
                if seconds(stamp) - changed > SETTLE:
                    rows.append((expression, np.array(values).reshape(-1, 6)))
    return bones, rows


def features(rows, eye):
    angles = np.array([r[1][eye, :3] for r in rows])
    pitch = np.clip(angles[:, 2], PITCH_MIN, PITCH_MAX)
    yaw = np.clip(angles[:, 0], -YAW_MAX, YAW_MAX)
    return np.c_[np.minimum(pitch, 0), np.maximum(pitch, 0), yaw, np.ones(len(pitch))]


def robust_fit(x, y):
    """Least squares that drops outliers (blinks) in a few passes."""
    keep = np.ones(len(y), bool)
    for _ in range(4):
        coef, *_ = np.linalg.lstsq(x[keep], y[keep], rcond=None)
        residual = np.abs(y - x @ coef)
        keep = residual < 6 * (np.median(residual[keep]) + 1e-4) + 0.05
    return coef


def number(value):
    text = f"{value:.4f}".rstrip("0")
    return "0." if text in ("-0.", "0.") else text


def main():
    bones, rows = read(sys.argv[1:])
    index = {name: i for i, name in enumerate(bones)}
    eyes = {"l": index["l_J_eye_JNT"], "r": index["r_J_eye_JNT"]}
    neutral_rows = [r for r in rows if r[0] == 0]

    models = {}
    for name in bones:
        if "eye_lid" not in name:
            continue
        x = features(neutral_rows, eyes[name[0]])
        y = np.array([r[1][index[name]] for r in neutral_rows])
        coef = np.array([robust_fit(x, y[:, c])[:3] for c in range(6)])
        if np.abs(coef[:3]).max() > 0.03 or np.abs(coef[3:]).max() > 0.002:  # bones that do follow the eyes
            models[name] = coef

    factors = np.ones((EXPRESSIONS, 2, 2, 2))
    for expression in range(EXPRESSIONS):
        chosen = [r for r in rows if r[0] == expression]
        if len(chosen) < 8:
            continue
        for s, side in enumerate("lr"):
            x = features(chosen, eyes[side])
            for g, group in enumerate(("up", "dn")):
                shares = []
                for n in (1, 2):
                    name = f"{side}_J_eye_lid_{group}_root_{n}_JNT"
                    coef = robust_fit(x, np.array([r[1][index[name], 2] for r in chosen]))
                    shares.append([coef[0] / models[name][2, 0], coef[1] / models[name][2, 1]])
                factors[expression, s, g] = np.clip(np.mean(shares, 0), 0.0, 1.1)

    out = [
        "// Generated by tools/eyelid_follow_fit.py from EyelidProbe measurements (game 2.31). Do not edit by hand.",
        "//",
        "// Per eyelid bone: change relative to the reference pose per degree of eye turn, for the turn down (pitch < 0),",
        "// up (pitch > 0) and sideways (yaw). Rows: turn x y z (degrees), move x y z (cm), in the bone's parent space.",
        "// Expression factors: share of that movement the game keeps with each facial expression of the base game:",
        "// [expression][left, right][upper, lower lid][eyes down, eyes up].",
        "",
        "constexpr LidBone LidBones[] = {",
    ]
    for name in sorted(models):
        coef = models[name]
        table = ", ".join("{" + ", ".join(number(v) + "f" for v in coef[c]) + "}" for c in range(6))
        out.append(f'    {{"{name}", {0 if name[0] == "l" else 1}, {0 if "_up_" in name else 1}, {{{table}}}}},')
    out += ["};", "", f"constexpr float ExpressionFactors[{EXPRESSIONS}][2][2][2] = {{"]
    for expression in range(EXPRESSIONS):
        sides = []
        for s in range(2):
            groups = ["{" + number(factors[expression, s, g, 0]) + "f, " + number(factors[expression, s, g, 1]) + "f}"
                      for g in range(2)]
            sides.append("{" + ", ".join(groups) + "}")
        out.append(f"    {{{', '.join(sides)}}}, // {expression}")
    out.append("};")
    print("\n".join(out))


if __name__ == "__main__":
    main()
